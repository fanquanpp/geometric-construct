import json, os

def R(x, y, w, h):  # rect
    return {"x": x, "y": y, "w": w, "h": h}

def P(x, y, w, h, **kw):  # platform dict
    p = {"rect": R(x, y, w, h)}
    p.update(kw)
    return p

def DECOR(x, y, w, h):
    return P(x, y, w, h, faces="none", tags=["back"])

def V(x, y):
    return {"x": x, "y": y}

def HINT(x, y, text, touch):
    return {"pos": V(x, y), "text": text, "touch": touch}

def ZONE(x, w, name, h=1080):
    return {"rect": R(x, 0, w, h), "name": name}

def level(name, focus, roster, intro, platforms, exits, spawns,
          checkpoints=(), hints=(), zones=None, size=(3200, 1080),
          note="", **extra):
    d = {
        "_title": name, "_note": note, "version": 1, "name": name,
        "focus": focus, "roster": roster, "intro": intro,
        "size": V(*size), "kill_y": 1400, "top_kill_y": -420,
        "platforms": platforms,
        "exits": [[g, V(*p)] for g, p in exits],
        "spawns": [None] * roster[0] +
                  [None if s is None else (s if isinstance(s, dict) else V(*s))
                   for s in spawns],
        "checkpoints": [{"pos": V(*c)} for c in checkpoints],
        "hints": list(hints),
        "zones": zones if zones is not None else [
            ZONE(0, size[0] // 3, "Z0 启程"),
            ZONE(size[0] // 3, size[0] // 3, "Z1 中段"),
            ZONE(size[0] * 2 // 3, size[0] - size[0] * 2 // 3, "Z2 归门"),
        ],
    }
    d.update(extra)
    return d

